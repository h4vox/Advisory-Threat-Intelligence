/**
 * Source registry (AIE Web Extraction spec §14, §15, §42, §66).
 *
 * Tier 1  structured / authoritative  (ATT&CK STIX, CISA KEV, government CERT advisories)
 * Tier 2  adversary emulation         (CTID library, Attack Flow corpus, Atomic Red Team, CALDERA)
 * Tier 3  high-quality research       (vendor / DFIR research blogs, structured IOC repos)
 * Tier 4  community                   (crawler / agent discovered sources — not seeded here)
 *
 * Acquisition preference follows spec §15: Git / STIX / JSON before RSS before HTML.
 * Feed URLs marked "unverified" are disabled until an analyst confirms them.
 */
export type SyncSchedule = "hourly" | "daily" | "weekly";

export type RegistrySource = Omit<SourceRecord, "lastIngestAt"> & {
  tier: SourceTier;
  connector: ConnectorType;
  yields: DocType[];
  /** Spec §42 trust class; numeric weight in SOURCE_CONFIDENCE. */
  confidenceClass: SourceConfidenceClass;
  /** How often the source is expected to change (sync / crawl hint). */
  schedule: SyncSchedule;
};

/** Connectors that are synced by a structured parser instead of the RSS/HTML crawler. */
export const STRUCTURED_CONNECTORS: ReadonlySet<ConnectorType> = new Set(["stix_bundle", "github_repo", "json_feed"]);

export function isStructuredSource(s: { connector?: ConnectorType }): boolean {
  return !!s.connector && STRUCTURED_CONNECTORS.has(s.connector);
}

