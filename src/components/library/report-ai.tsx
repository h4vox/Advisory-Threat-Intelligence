const ACTION_TOAST: Record<string, string> = {
  keep: "Analysed: useful threat intelligence.",
  flag: "Analysed and flagged for you to decide (Needs review).",
  hide: "Analysed and hidden: the AI is confident this is not threat research and nothing in it protects it. Restore it from Hidden if that is wrong.",
  restore_and_flag: "Analysed: restored to the library and flagged for you to confirm.",
  unchanged: "Analysed. The report's visibility is unchanged.",
};

/** Runs the grounded AI analysis of one report and refreshes the page. */
export function AnalyseWithAiButton({ reportId, analysed, variant }: { reportId: string; analysed: boolean; variant?: "primary" | "ghost" }) {
  const qc = useQueryClient();
  const [busy, setBusy] = useState(false);
  const run = async () => {
    setBusy(true);
    const tid = toast.loading("Analysing the report with AI… this can take a minute.");
    try {
      const res = await analyseReportWithAi({ data: { id: reportId } });
      if (!res.ok) {
        toast.error(res.error, { id: tid });
        return;
      }
      const removed = res.dropped.iocs + res.dropped.steps + res.dropped.findings + res.dropped.adversaryTerms + res.dropped.summarySentences;
      toast.success(ACTION_TOAST[res.action] ?? "Analysed.", {
        id: tid,
        description: removed > 0 ? `${removed} item${removed === 1 ? "" : "s"} the report text does not support ${removed === 1 ? "was" : "were"} left out.` : res.reason,
      });
      for (const key of ["report", "reports-all", "reports-search", "nav-counts", "dashboard"]) void qc.invalidateQueries({ queryKey: [key] });
    } catch (err) {
      toast.error(`AI analysis failed: ${err instanceof Error ? err.message : "unknown error"}`, { id: tid });
    } finally {
      setBusy(false);
    }
  };
  return (
    <ActionButton variant={variant} icon={Sparkles} disabled={busy} onClick={() => void run()}>
      {busy ? "Analysing…" : analysed ? "Analyse again" : "Analyse with AI"}
    </ActionButton>
  );
}

/** Where the AI output came from, and how much the grounding check removed. */
export function AiProvenance({ ai }: { ai: ReportAiAnalysis }) {
  const d = ai.dropped;
  const removed = d.iocs + d.steps + d.findings + d.adversaryTerms + d.summarySentences;
  return (
    <p className="mt-3 text-xs text-subtle">
      AI-generated by {ai.provider} on {formatDateTime(ai.analysedAt)}, checked against the report text
      {removed > 0 ? `: ${removed} unsupported item${removed === 1 ? "" : "s"} left out` : ""}.
      {ai.truncated ? " Only the first part of this long report was analysed." : ""}
    </p>
  );
}

export function AiSummary({ ai }: { ai: ReportAiAnalysis }) {
  return (
    <div>
      {ai.summary ? (
        <p className="max-w-4xl text-[15px] leading-relaxed text-fg/90">{ai.summary}</p>
      ) : (
        <p className="text-sm text-subtle">The AI summary did not survive the check against the report text.</p>
      )}
      {ai.keyFindings.length > 0 && (
        <div className="mt-5">
          <h3 className="mb-2 text-sm font-medium text-fg">Key findings</h3>
          <ul className="divide-y divide-border rounded-xl border border-border bg-bg-card">
            {ai.keyFindings.map((f, i) => (
              <li key={i} className="grid gap-1.5 px-4 py-3 md:grid-cols-[minmax(0,1fr)_minmax(0,1fr)] md:gap-5">
                <p className="text-sm text-fg">{f.text}</p>
                <blockquote className="min-w-0 break-words border-l-2 border-border pl-3 text-xs text-muted">{f.quote}</blockquote>
              </li>
            ))}
          </ul>
        </div>
      )}
      <AiProvenance ai={ai} />
    </div>
  );
}

/** The attack chain as the intrusion unfolded, one stage after another, each with its source sentence. */
export function AiAttackFlow({ ai }: { ai: ReportAiAnalysis }) {
  if (ai.attackChain.length === 0) {
    return <p className="text-sm text-subtle">The AI found no attack sequence the report text supports.</p>;
  }
  return (
    <div>
      <ol className="space-y-0">
        {ai.attackChain.map((s, i) => (
          <li key={`${s.order}-${s.stage}`}>
            <div className="rounded-xl border border-border bg-bg-card px-4 py-3.5 sm:px-5">
              <div className="flex flex-wrap items-center gap-x-3 gap-y-1.5">
                <span className="flex size-6 shrink-0 items-center justify-center rounded-full bg-bg-subtle text-xs font-medium tabular-nums text-muted">{s.order}</span>
                <span className="text-sm font-medium text-fg">{s.stage}</span>
                {s.technique && (
                  <span className="inline-flex items-center gap-1.5 rounded-md bg-bg-subtle px-2 py-0.5 text-xs text-fg">
                    <span className="font-mono text-muted">{s.technique.id}</span>
                    <span>{s.technique.name}</span>
                  </span>
                )}
              </div>
              <p className="mt-2 text-sm text-muted">{s.summary}</p>
              <blockquote className="mt-2 break-words border-l-2 border-border pl-3 text-xs text-subtle">{s.quote}</blockquote>
            </div>
            {i < ai.attackChain.length - 1 && (
              <div className="flex justify-center py-1 text-subtle" aria-hidden>
                <ArrowDown className="size-4" strokeWidth={1.75} />
              </div>
            )}
          </li>
        ))}
      </ol>
      <AiProvenance ai={ai} />
    </div>
  );
}

function Terms({ items, empty }: { items: string[]; empty: string }) {
  if (!items.length) return <span className="text-subtle">{empty}</span>;
  return (
    <span className="flex flex-wrap gap-1.5">
      {items.map((t) => (
        <span key={t} className="rounded-md bg-bg-subtle px-2 py-0.5 text-xs text-fg">
          {t}
        </span>
      ))}
    </span>
  );
}

