/** Indicators the AI found in the report that the extractor did not list (each verified in the text). */
export function AiExtraIocs({ ai, iocs }: { ai: ReportAiAnalysis; iocs: IocHit[] }) {
  const known = new Set(iocs.map((i) => i.value.toLowerCase()));
  const extra = ai.iocs.filter((i) => !known.has(i.value.toLowerCase()));
  const confirmed = ai.iocs.length - extra.length;
  return (
    <div>
      <p className="mb-3 text-sm text-muted">
        {ai.iocs.length === 0
          ? "The AI listed no indicators the report text supports."
          : `${confirmed} of the AI's ${ai.iocs.length} indicators match the extracted list${extra.length ? `; ${extra.length} more ${extra.length === 1 ? "is" : "are"} listed below` : ""}.`}
      </p>
      {extra.length > 0 && (
        <ul className="divide-y divide-border rounded-xl border border-border bg-bg-card">
          {extra.map((i) => (
            <li key={`${i.type}:${i.value}`} className="grid gap-1 px-4 py-2.5 sm:grid-cols-[7rem_minmax(0,1fr)_minmax(0,14rem)] sm:gap-4">
              <span className="text-xs text-muted">{AI_IOC_LABEL[i.type] ?? i.type}</span>
              <span className="break-all font-mono text-[13px] text-fg">{i.value}</span>
              <span className="text-xs text-subtle">{i.context ?? ""}</span>
            </li>
          ))}
        </ul>
      )}
      <AiProvenance ai={ai} />
    </div>
  );
}

const ACTION_LABEL: Record<string, { label: string; tone: "success" | "warning" | "neutral" | "info" }> = {
  keep: { label: "Useful", tone: "success" },
  flag: { label: "Needs review", tone: "warning" },
  restore_and_flag: { label: "Restored · needs review", tone: "warning" },
  hide: { label: "Hidden by the AI review", tone: "neutral" },
  unchanged: { label: "Reviewed", tone: "info" },
};

/** The latest review decision, with Keep / Hide for an analyst while it needs review. */
export function ReviewStatus({ reportId, review, needsReview }: { reportId: string; review?: ReportReviewView; needsReview?: boolean }) {
  const qc = useQueryClient();
  const [busy, setBusy] = useState(false);
  if (!review) return null;
  const meta = needsReview ? ACTION_LABEL.flag : review.by === "analyst" ? { label: "Decided by an analyst", tone: "success" as const } : ACTION_LABEL[review.action] ?? ACTION_LABEL.unchanged;
  const resolve = async (decision: "keep" | "hide") => {
    setBusy(true);
    try {
      const res = await resolveReportReview({ data: { id: reportId, decision } });
      if (!res.ok) toast.error("The review could not be saved.");
      else toast.success(decision === "keep" ? "Kept: the rules and the AI review will not hide it." : "Hidden. Restore it from Hidden at any time.");
      for (const key of ["report", "reports-all", "reports-search", "nav-counts"]) void qc.invalidateQueries({ queryKey: [key] });
    } finally {
      setBusy(false);
    }
  };
  return (
    <div className={cn("rounded-xl border px-4 py-3", needsReview ? "border-[color-mix(in_oklab,var(--color-warn)_50%,transparent)] bg-[color-mix(in_oklab,var(--color-warn)_6%,transparent)]" : "border-border bg-bg-card")}>
      <div className="flex flex-wrap items-center justify-between gap-3">
        <StatusChip tone={meta.tone} dot>
          {meta.label}
        </StatusChip>
        {needsReview && (
          <div className="flex flex-wrap gap-2">
            <ActionButton icon={Check} disabled={busy} onClick={() => void resolve("keep")} title="Keep it; the rules and the AI review will not hide it">
              Keep
            </ActionButton>
            <ActionButton icon={EyeOff} disabled={busy} onClick={() => void resolve("hide")} title="Hide it; restore it from Hidden at any time">
              Hide
            </ActionButton>
          </div>
        )}
      </div>
      <p className="mt-2 text-sm text-muted">{review.reason}</p>
      {review.reviewedAt && <p className="mt-1 text-xs text-subtle">{formatDateTime(review.reviewedAt)}</p>}
    </div>
  );
}
